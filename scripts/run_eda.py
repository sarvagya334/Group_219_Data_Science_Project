def load_series():
    prices = {}
    for name, filename in INDEX_FILES.items():
        path = CLEAN / filename
        if not path.exists():
            raise FileNotFoundError(f"Missing {path}. Run `make clean-validate` first.")
        df = pd.read_csv(path, parse_dates=["Date"])
        if not {"Date", "Close"}.issubset(df.columns):
            raise ValueError(f"{path} must contain Date and Close columns")
        df = df.sort_values("Date").drop_duplicates("Date")
        if df["Date"].isna().any() or df["Close"].isna().any() or (df["Close"] <= 0).any():
            raise ValueError(f"Invalid dates or close prices in {path}")
        prices[name] = df.set_index("Date")["Close"].astype(float).rename(name)
    # Restrict direct comparisons to the shared dates. Report intersection size.
    price_df = pd.concat(prices.values(), axis=1, join="inner").dropna().sort_index()
    if price_df.empty:
        raise ValueError("No common dates across index datasets")
    returns = price_df.pct_change(fill_method=None).dropna() * 100.0  # percentage points
    return price_df, returns


def max_drawdown(close: pd.Series):
    wealth = close / close.iloc[0]
    dd = wealth / wealth.cummax() - 1.0
    trough = dd.idxmin()
    peak = wealth.loc[:trough].idxmax()
    peak_val = wealth.loc[peak]
    post = wealth.loc[trough:]
    recovery_dates = post.index[post >= peak_val]
    recovery_days = int((recovery_dates[0] - trough).days) if len(recovery_dates) else None
    return float(dd.min() * 100), peak, trough, recovery_days, dd


def hac_intercept_test(values: pd.Series, maxlags: int = 5):
    """Test mean(value)=0 with Newey-West/HAC standard errors."""
    x = pd.Series(values).dropna().astype(float)
    if len(x) < 30 or x.std(ddof=1) == 0:
        return {"n": int(len(x)), "estimate": float(x.mean()) if len(x) else None,
                "se_hac": None, "ci95_low": None, "ci95_high": None, "p_value": None,
                "status": "insufficient_or_constant_data"}
    model = sm.OLS(x.to_numpy(), np.ones((len(x), 1))).fit(cov_type="HAC", cov_kwds={"maxlags": min(maxlags, max(1, len(x)//4))})
    ci = model.conf_int(alpha=0.05)[0]
    return {"n": int(len(x)), "estimate": float(model.params[0]), "se_hac": float(model.bse[0]),
            "ci95_low": float(ci[0]), "ci95_high": float(ci[1]), "p_value": float(model.pvalues[0]),
            "status": "tested", "standard_error": "Newey-West HAC; maxlags up to 5"}


def holm_adjust(p_values):
    """Holm step-down family-wise error adjustment; None p-values remain None."""
    out = [None] * len(p_values)
    valid = [(i, p) for i, p in enumerate(p_values) if p is not None and np.isfinite(p)]
    valid.sort(key=lambda z: z[1])
    m = len(valid)
    running = 0.0
    for rank, (i, p) in enumerate(valid):
        adjusted = min(1.0, (m - rank) * float(p))
        running = max(running, adjusted)
        out[i] = running
    return out


def write_json(path, obj):
    path.write_text(json.dumps(obj, indent=2, allow_nan=False, default=str), encoding="utf-8")


def main():
    for d in (EDA_DIR, TEST_DIR, FIG_DIR): d.mkdir(parents=True, exist_ok=True)
    prices, returns = load_series()
    index_names = list(prices.columns)
    start, end = prices.index.min(), prices.index.max()
    n_sessions = len(prices)

    # Descriptive summary. Annualized volatility assumes 252 trading observations/year.
    descriptive = {}
    for name in index_names:
        r = returns[name].dropna()
        dd_pct, peak, trough, recovery_days, dd_series = max_drawdown(prices[name])
        descriptive[name] = {
            "price_observations": int(prices[name].notna().sum()),
            "return_observations": int(r.notna().sum()),
            "first_date": prices[name].index.min().strftime("%Y-%m-%d"),
            "last_date": prices[name].index.max().strftime("%Y-%m-%d"),
            "start_close": float(prices[name].iloc[0]),
            "end_close": float(prices[name].iloc[-1]),
            "cumulative_return_pct": float((prices[name].iloc[-1] / prices[name].iloc[0] - 1) * 100),
            "mean_daily_return_pct": float(r.mean()),
            "median_daily_return_pct": float(r.median()),
            "daily_return_std_pct": float(r.std(ddof=1)),
            "annualized_volatility_pct": float(r.std(ddof=1) * np.sqrt(252)),
            "annualized_mean_return_pct_simple": float(r.mean() * 252),
            "skewness": float(r.skew()),
            "excess_kurtosis": float(r.kurt()),
            "min_daily_return_pct": float(r.min()),
            "p01_daily_return_pct": float(r.quantile(0.01)),
            "p05_daily_return_pct": float(r.quantile(0.05)),
            "p95_daily_return_pct": float(r.quantile(0.95)),
            "p99_daily_return_pct": float(r.quantile(0.99)),
            "max_daily_return_pct": float(r.max()),
            "negative_day_fraction_pct": float((r < 0).mean() * 100),
            "mean_return_on_negative_days_pct": float(r[r < 0].mean()) if (r < 0).any() else None,
            "worst_5_session_compound_return_pct": float(((1 + r/100).rolling(5).apply(np.prod, raw=True).dropna().min() - 1) * 100),
            "worst_20_session_compound_return_pct": float(((1 + r/100).rolling(20).apply(np.prod, raw=True).dropna().min() - 1) * 100),
            "maximum_drawdown_pct": dd_pct,
            "drawdown_peak_date": peak.strftime("%Y-%m-%d"),
            "drawdown_trough_date": trough.strftime("%Y-%m-%d"),
            "recovery_days_after_max_drawdown": recovery_days,
        }

    summary = {
        "title": "Comparative EDA of NSE sector/industry indices",
        "generated_by": "scripts/run_eda.py",
        "date_range": {"start": start.strftime("%Y-%m-%d"), "end": end.strftime("%Y-%m-%d")},
        "common_price_observations": int(n_sessions),
        "common_return_observations": int(len(returns)),
        "return_definition": "Close-to-close simple percentage return: 100*(Close_t/Close_(t-1)-1)",
        "annualization_factor": 252,
        "indices": descriptive,
        "interpretation_notes": [
            "Price return indices are analyzed as supplied; if the source is not a total-return index, results exclude dividends.",
            "Normalized cumulative performance starts at the first common date and is descriptive, not a forecast.",
            "Annualized mean is a simple scaling of daily arithmetic mean, not a compounded CAGR.",
            "Maximum drawdown is computed over the available sample only; recovery_days is null if the previous peak was not recovered by the end of the sample.",
            "Overlapping index universes mean the series are not independent portfolios or independent observations.",
            "Common-date alignment is not proof that every official NSE trading session is present.",
        ],
    }
    write_json(EDA_DIR / "descriptive_statistics.json", summary)

    # CSV tables useful for notebooks/downstream analysis.
    prices.to_csv(EDA_DIR / "common_date_closes.csv", date_format="%Y-%m-%d")
    returns.to_csv(EDA_DIR / "daily_returns_pct.csv", date_format="%Y-%m-%d", float_format="%.8f")
    normalized = prices.divide(prices.iloc[0]).multiply(100)
    normalized.to_csv(EDA_DIR / "normalized_prices_base100.csv", date_format="%Y-%m-%d", float_format="%.8f")
    corr = returns.corr(method="pearson")
    corr.to_csv(EDA_DIR / "return_correlation_matrix.csv", float_format="%.8f")
    corr_s = returns.corr(method="spearman")
    corr_s.to_csv(EDA_DIR / "return_spearman_correlation_matrix.csv", float_format="%.8f")

    # Figures: separate, reproducible charts.
    plt.figure(figsize=(12, 6))
    normalized.plot(ax=plt.gca(), linewidth=1.15)
    plt.title("Normalized index performance (first common close = 100)")
    plt.xlabel("Date"); plt.ylabel("Index level (base 100)"); plt.grid(True, alpha=.25); plt.tight_layout()
    plt.savefig(FIG_DIR / "01_normalized_performance.png", dpi=160); plt.close()

    plt.figure(figsize=(12, 6))
    returns.plot(ax=plt.gca(), alpha=.65, linewidth=.7)
    plt.title("Daily close-to-close returns")
    plt.xlabel("Date"); plt.ylabel("Daily return (%)"); plt.grid(True, alpha=.25); plt.tight_layout()
    plt.savefig(FIG_DIR / "02_daily_returns.png", dpi=160); plt.close()

    plt.figure(figsize=(10, 6))
    returns.boxplot(ax=plt.gca(), showfliers=False, grid=False)
    plt.title("Daily return distributions (outliers hidden for readability; retained in statistics)")
    plt.ylabel("Daily return (%)"); plt.xticks(rotation=15); plt.tight_layout()
    plt.savefig(FIG_DIR / "03_return_boxplots.png", dpi=160); plt.close()

    plt.figure(figsize=(12, 6))
    (returns.rolling(20).std() * np.sqrt(252)).plot(ax=plt.gca(), linewidth=1.1)
    plt.title("20-session rolling annualized volatility")
    plt.xlabel("Date"); plt.ylabel("Annualized volatility (%)"); plt.grid(True, alpha=.25); plt.tight_layout()
    plt.savefig(FIG_DIR / "04_rolling_volatility_20d.png", dpi=160); plt.close()

    plt.figure(figsize=(12, 6))
    (returns.rolling(60).std() * np.sqrt(252)).plot(ax=plt.gca(), linewidth=1.1)
    plt.title("60-session rolling annualized volatility")
    plt.xlabel("Date"); plt.ylabel("Annualized volatility (%)"); plt.grid(True, alpha=.25); plt.tight_layout()
    plt.savefig(FIG_DIR / "05_rolling_volatility_60d.png", dpi=160); plt.close()

    plt.figure(figsize=(10, 7))
    im = plt.imshow(corr.to_numpy(), vmin=-1, vmax=1, aspect="auto")
    plt.colorbar(im, label="Pearson correlation")
    plt.xticks(range(len(index_names)), index_names, rotation=25, ha="right")
    plt.yticks(range(len(index_names)), index_names)
    for i in range(len(index_names)):
        for j in range(len(index_names)):
            plt.text(j, i, f"{corr.iloc[i,j]:.2f}", ha="center", va="center")
    plt.title("Correlation of daily index returns"); plt.tight_layout()
    plt.savefig(FIG_DIR / "06_return_correlation_heatmap.png", dpi=160); plt.close()

    plt.figure(figsize=(12, 6))
    for name in index_names:
        wealth = (1 + returns[name] / 100).cumprod()
        drawdown = (wealth / wealth.cummax() - 1) * 100
        plt.plot(drawdown.index, drawdown, label=name, linewidth=1.0)
    plt.title("Drawdown from running peak")
    plt.xlabel("Date"); plt.ylabel("Drawdown (%)"); plt.legend(); plt.grid(True, alpha=.25); plt.tight_layout()
    plt.savefig(FIG_DIR / "07_drawdowns.png", dpi=160); plt.close()

    # Pairwise hypotheses with HAC standard errors and Holm adjustment across each family.
    tests = []
    pairwise_correlations = []
    for a, b in combinations(index_names, 2):
        diff = returns[a] - returns[b]
        mean_test = hac_intercept_test(diff)
        # Absolute returns are a robust descriptive proxy for scale/volatility; test mean difference.
        abs_test = hac_intercept_test(returns[a].abs() - returns[b].abs())
        # Negative-day return severity is compared on dates when either index is negative.
        both = pd.concat([returns[a], returns[b]], axis=1).dropna()
        downside_mask = (both[a] < 0) | (both[b] < 0)
        downside_test = hac_intercept_test((both.loc[downside_mask, a] - both.loc[downside_mask, b]))
        tests.append({"index_a": a, "index_b": b, "hypothesis_family": "H1_mean_daily_return_difference",
                      "H0": "Mean daily return difference (A-B) equals zero", "H1": "Mean daily return difference (A-B) is not zero",
                      **mean_test})
        tests.append({"index_a": a, "index_b": b, "hypothesis_family": "H2_absolute_return_difference",
                      "H0": "Mean absolute daily return difference (A-B) equals zero", "H1": "Mean absolute daily return difference (A-B) is not zero",
                      **abs_test})
        tests.append({"index_a": a, "index_b": b, "hypothesis_family": "H3_downside_return_difference",
                      "H0": "Mean A-B return difference on dates when either index is negative equals zero", "H1": "That conditional mean difference is not zero",
                      **downside_test, "conditional_sample_definition": "Dates where A < 0 or B < 0"})
        pairwise_correlations.append({"index_a": a, "index_b": b, "pearson_correlation": float(returns[a].corr(returns[b])),
                                      "spearman_correlation": float(returns[a].corr(returns[b], method="spearman")),
                                      "n": int(both.shape[0])})

    # Holm correction within each family (120 pairwise comparisons per family for 16 indices).
    for family in sorted({t["hypothesis_family"] for t in tests}):
        group = [t for t in tests if t["hypothesis_family"] == family]
        adjusted = holm_adjust([t.get("p_value") for t in group])
        for t, p_adj in zip(group, adjusted):
            t["p_value_holm"] = p_adj
            t["alpha"] = 0.05
            t["reject_h0_after_holm"] = bool(p_adj is not None and p_adj < 0.05)

    test_report = {
        "title": "Pairwise cross-index hypotheses",
        "generated_by": "scripts/run_eda.py",
        "date_range": {"start": start.strftime("%Y-%m-%d"), "end": end.strftime("%Y-%m-%d")},
        "common_return_observations": int(len(returns)),
        "inference": "OLS intercept with Newey-West HAC standard errors (up to 5 lags); Holm correction within each of the three hypothesis families; two-sided tests; alpha=0.05.",
        "hypotheses": {
            "H1_mean_daily_return_difference": "For each pair of indices A,B, H0: E[r_A-r_B]=0. H1: E[r_A-r_B] != 0.",
            "H2_absolute_return_difference": "For each pair, H0: E[|r_A|-|r_B|]=0. Absolute return is a volatility-intensity proxy, not the standard deviation itself.",
            "H3_downside_return_difference": "For each pair, compare A-B returns conditional on at least one index having a negative return that session. This is descriptive conditional inference, not a standalone tail-risk model.",
        },
        "pairwise_tests": tests,
        "pairwise_correlations": pairwise_correlations,
        "limitations": [
            "These tests compare index-level return series; they do not test causal effects of macroeconomic variables.",
            "HAC errors address some serial dependence in the mean-difference series but do not solve all model misspecification or structural-break concerns.",
            "The index series overlap in constituents, so they are not independent portfolios; pairwise paired-difference design is used deliberately.",
            "Holm correction is applied separately within each hypothesis family, not across every statistic in the project.",
            "Results are sensitive to sample period, return convention, index methodology changes and data quality.",
            "The conditional downside test is not equivalent to a formal expected-shortfall or tail-dependence test.",
        ],
    }
    write_json(TEST_DIR / "cross_index_hypothesis_tests.json", test_report)
    pd.DataFrame(tests).to_csv(TEST_DIR / "cross_index_hypothesis_tests.csv", index=False)
    pd.DataFrame(pairwise_correlations).to_csv(EDA_DIR / "pairwise_correlations.csv", index=False)

    # Markdown report with metrics, explanations and automatically generated test outcomes.
    lines = [
        "# Comparative EDA and Cross-Index Hypothesis Tests", "",
        f"**Observed sample:** {start:%Y-%m-%d} to {end:%Y-%m-%d}.", 
        f"**Common closes:** {n_sessions:,}; **close-to-close return observations:** {len(returns):,}.", "",
        "## Executive summary", "",
        "This report compares 16 long-history NSE sector/industry index series on common dates. It describes performance, return distributions, volatility, correlation and drawdowns, then tests paired differences in mean returns, absolute returns and conditional downside returns.", "",
        "This is index-level descriptive/inferential analysis. It is not a causal analysis of macroeconomic events and does not establish a profitable trading strategy.", "",
        "## Descriptive statistics", "",
        "Returns are simple close-to-close percentage changes. Annualized volatility is daily standard deviation multiplied by sqrt(252). Annualized mean return is the arithmetic daily mean multiplied by 252 and is not CAGR.", "",
        "| Index | Cumulative return (%) | Annualized volatility (%) | Mean daily return (%) | Skew | Excess kurtosis | Max drawdown (%) | Worst 5-session return (%) |", "|---|---:|---:|---:|---:|---:|---:|---:|"
    ]
    for name, d in descriptive.items():
        lines.append(f"| {name} | {d['cumulative_return_pct']:.2f} | {d['annualized_volatility_pct']:.2f} | {d['mean_daily_return_pct']:.4f} | {d['skewness']:.3f} | {d['excess_kurtosis']:.3f} | {d['maximum_drawdown_pct']:.2f} | {d['worst_5_session_compound_return_pct']:.2f} |")
    lines += ["", "## Figures", "",
              "1. `reports/figures/01_normalized_performance.png`: all selected sector indices rebased to 100 at the first common close.",
              "2. `reports/figures/02_daily_returns.png`: daily returns over time.",
              "3. `reports/figures/03_return_boxplots.png`: return distributions; plotted outliers are hidden for readability but retained in calculations.",
              "4. `reports/figures/04_rolling_volatility_20d.png` and `05_rolling_volatility_60d.png`: rolling annualized volatility.",
              "5. `reports/figures/06_return_correlation_heatmap.png`: Pearson return correlation matrix.",
              "6. `reports/figures/07_drawdowns.png`: drawdown from running peak.", "",
              "## EDA interpretation guide", "",
              "- **Normalized performance:** compares growth of 1 unit invested in each price series from a shared start; it does not account for dividends unless the source index itself does.",
              "- **Return distributions:** skewness indicates asymmetry; excess kurtosis indicates heavier/lighter tails than a Gaussian distribution. Extreme observations should be source-checked, not automatically deleted.",
              "- **Rolling volatility:** shows time-varying risk; 20-session estimates react faster and are noisier than 60-session estimates.",
              "- **Correlation:** high positive correlation means daily returns often move together, not that one causes the other. Overlapping constituents naturally raise dependence.",
              "- **Drawdown:** loss from the prior running peak. Recovery time is measured in calendar days after the maximum-drawdown trough, and is null if not recovered by sample end.",
              "- **Stress metrics:** worst 5/20-session returns are descriptive sample extrema and can be sensitive to the chosen period.", "",
              "## Cross-index hypothesis testing", "",
              "The test runner uses paired return differences because indices are observed on the same dates and have overlapping constituents. Each pairwise difference series is tested with an intercept-only OLS model using Newey-West/HAC standard errors with up to five lags. Holm correction is applied within each family of 120 pairwise comparisons. Alpha is 0.05.", "",
              "### H1 — Mean daily return difference", "",
              "For each pair A and B: H0: E[r_A − r_B] = 0; H1: E[r_A − r_B] ≠ 0. The estimate is in percentage points per day. A statistically significant result does not automatically imply an economically meaningful difference.", "",
              "### H2 — Absolute-return intensity difference", "",
              "For each pair: H0: E[|r_A| − |r_B|] = 0. Absolute return is used as a scale/volatility-intensity proxy. It is not the same as testing equality of variance or annualized standard deviation.", "",
              "### H3 — Conditional downside-return difference", "",
              "For each pair: compare r_A − r_B on dates when at least one index has a negative return. This asks whether the relative return differs on down days for at least one index. It is not a formal tail-dependence or CVaR test.", "",
              "### Results", "",
              "| Family | Pair | Estimate (pp/day) | HAC 95% CI | Raw p-value | Holm p-value | Decision at 5% | n |", "|---|---|---:|---|---:|---:|---|---:|"]
    for t in tests:
        ci = "—" if t.get("ci95_low") is None else f"[{t['ci95_low']:.5f}, {t['ci95_high']:.5f}]"
        p = "—" if t.get("p_value") is None else f"{t['p_value']:.4g}"
        pa = "—" if t.get("p_value_holm") is None else f"{t['p_value_holm']:.4g}"
        decision = "Reject H0" if t.get("reject_h0_after_holm") else "Do not reject H0"
        lines.append(f"| {t['hypothesis_family']} | {t['index_a']} − {t['index_b']} | {t.get('estimate', float('nan')):.5f} | {ci} | {p} | {pa} | {decision} | {t['n']} |")
    lines += ["", "## Correlation summary", "", "| Pair | Pearson r | Spearman rho | n |", "|---|---:|---:|---:|"]
    for c in pairwise_correlations:
        lines.append(f"| {c['index_a']} — {c['index_b']} | {c['pearson_correlation']:.4f} | {c['spearman_correlation']:.4f} | {c['n']} |")
    lines += ["", "## Important limitations", "",
              "1. **Calendar completeness:** matching dates across indices does not certify that every official NSE trading session is present.",
              "2. **Index overlap:** Sector index series may share constituents and common market shocks; paired-difference tests should not be interpreted as independent portfolio samples.",
              "3. **Price-return vs total-return:** source index type should be confirmed. Dividend treatment can materially change long-horizon comparisons.",
              "4. **Index reconstitution:** constituents and methodology may change over the sample, so these are historical index-level returns rather than a fixed-company panel.",
              "5. **Multiple comparisons:** Holm adjustment is within each stated family; broader exploratory analysis can still inflate false-positive risk.",
              "6. **Time-series assumptions:** HAC inference is robust to some autocorrelation/heteroskedasticity but not every structural break or model misspecification.",
              "7. **No macroeconomic testing here:** the current multi-index archive contains index OHLC CSVs only. Tests of USD/INR, CPI, RBI rates, reserves or S&P 500 require a separately audited, correctly aligned macro dataset.",
              "8. **No causal or investment claim:** association and historical differences do not establish causal mechanisms or future profitability.", "",
              "## Reproducibility", "",
              "Run `make all` for data cleaning and date audit, `make eda` for EDA and tests, `make test` for automated checks, or `make full` for the entire workflow. Outputs are written to `reports/eda/`, `reports/hypothesis_tests/` and `reports/figures/`.", ""]
    (REPORTS / "comparative_eda_and_hypothesis_report.md").write_text("\n".join(lines), encoding="utf-8")

    print(json.dumps({"date_range": [start.strftime("%Y-%m-%d"), end.strftime("%Y-%m-%d")],
                      "common_closes": int(n_sessions), "return_rows": int(len(returns)),
                      "descriptive_report": str(EDA_DIR / "descriptive_statistics.json"),
                      "hypothesis_report": str(TEST_DIR / "cross_index_hypothesis_tests.json"),
                      "markdown_report": str(REPORTS / "comparative_eda_and_hypothesis_report.md"),
                      "figures": sorted(p.name for p in FIG_DIR.glob("*.png"))}, indent=2))

if __name__ == "__main__":
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=FutureWarning)
        main()
